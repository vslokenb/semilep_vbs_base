print("")
print("status/covQual: these fits run strategy-0 migrad + MINOS (--minos all)")
print("with --robustHesse 1 backing the errors, so the status words are NOT")
print("meaningful (expect 300/-1 even for good fits). Judge the fits by the")
print("numbers instead: norms stable and consistent between the per-category,")
print("per-topology and shared cases, nothing pinned at a range edge, and no")
print("0.0000 errors (a zero error here makes read_cr_norms abort step 5d).")
