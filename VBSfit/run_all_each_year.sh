# Run one combine fit with its full log kept. $1 = log file, rest = combine
# arguments. A "| tail" pipe would both hide mid-log warnings (which is how
# the zero-error-band bug survived unnoticed: combine SAYS it is dropping
# --saveWithUncertainties, mid-log) and defeat set -e (the pipe's exit status
# is tail's, not combine's).
run_combine_logged() {
    local logf="$1"; shift
    # stdbuf -oL: line-buffer combine's stdout into the log. Redirected cout
    # is otherwise block-buffered, so during a long silent phase the log can
    # sit untouched for hours and look like a hang while combine is working.
    if ! stdbuf -oL -eL combine "$@" > "${logf}" 2>&1; then
        echo "ERROR: combine failed -- last 20 lines of ${logf}:"
        tail -20 "${logf}"
        exit 1
    fi
    tail -3 "${logf}"
}

# Abort if combine dropped --saveWithUncertainties. It does so whenever the
# fit covariance is not accurate for every parameter, writing every shape
# with zero bin errors and announcing it only mid-log:
#   "The option --saveWithUncertainties will be ignored ..."
check_band_saved() {
    local logf="$1"
    if grep -q "saveWithUncertainties will be ignored" "${logf}"; then
        echo "ERROR: combine ignored --saveWithUncertainties in ${logf}:"
        grep -m1 "saveWithUncertainties will be ignored" "${logf}"
        echo "       The file would carry ZERO-error postfit bands."
        echo "       The fit runs with --robustHesse 1 precisely to avoid"
        echo "       this; if it still fires, inspect the full log."
        exit 1
    fi
}


