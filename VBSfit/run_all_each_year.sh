    echo ""
    echo "  CR-only norms written to ${outfile}"
}


# Topology cards are produced by combineCards.py.
# The argument order here fixes the ch1_/ch2_ prefixes used in CR_MASKS above.
#
# ABSOLUTE input paths are required. combineCards.py rewrites each card's
# "shapes" line by prefixing it with the input card's directory exactly as
# given on the command line. With relative inputs the result is only valid
# when cwd happens to be CARDDIR, and text2workspace.py (run from VBSFIT_DIR)
# then fails with e.g.
#     Failed to open file resolved_mu/../../histograms/histograms_cr.root
# Absolute inputs make the shapes path absolute and cwd-independent.
# Confirm combine actually attached the normalization rateParams.
#
# make_datacards.py writes them with a wildcard bin field ("*resolved*"), which
# relies on combine interpreting that pattern the way fnmatch does. If it does
# not, the rateParam silently covers nothing: the fit still runs, norm_* sits
# at 1.0 with no constraint, and the CR data never reaches the normalization.
# That failure is invisible in the fit output, so check it once here.
check_rateparams_in_workspace() {
    local card="$1"
    local ws="${CARDDIR}/.rateparam_check.root"
    echo ""
    echo "--- Checking normalization rateParams reach the workspace ---"
    if ! text2workspace.py "${card}" -o "${ws}" -m ${MASS} > /dev/null 2>&1; then
        echo "  [warn] text2workspace failed on ${card}; skipping check."
        return 0
    fi
    python3 "${VBSFIT_DIR}/python/check_rateparams.py" "${ws}" "${card}"
    rm -f "${ws}"
}


