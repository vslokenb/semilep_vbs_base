#!/bin/bash
# Run full simultaneous SR+CR fit pipeline:
#   1. Build histograms (SRs + TTCRs + WCRs)
#   2. Make datacards with rateParams for norm_top and norm_wjet
#   3. Kinematics histograms + systematic ratio plots
#   4. Expected significance, MC-only Asimov reference (combined + per-SR)
#   5. FitDiagnostics, MC-only Asimov reference (combined)
#  5b. Uncertainty breakdown per category, MC-only Asimov
#      (OFF by default -- see BREAKDOWN_RUNS)
#  5c. CR-only fits on REAL DATA with the SRs masked (--channel-masks)
#  5d. Build the HYBRID dataset: real data in the CRs, MC pseudo-data in the SRs
#  5e. Significance / FitDiagnostics / impacts on the hybrid dataset
#  5f. Uncertainty breakdown per category, CR data included (the default)
#   6. Stacked pre-fit plots
#   7. Post-fit plots
#  5g. CR closure: postfit CR BDT shape vs data (CRs are counting bins in
#      the fit, so their shape is never fitted -- this checks it)
#   8. Impact plots, MC-only Asimov reference (combined + per-SR)
#   9. mjj_vbs sanity fits, Asimov significance only (--with-mjj)
#
# Usage:
#   ./run_all.sh                    # everything (default year 2018)
#   ./run_all.sh --year=2017        # process another data-taking period: the
#                                   # inputs config is per-year and EVERY output
#                                   # path (histograms, cards, plots) is tagged
#                                   # with the year -- one datacard per category
#                                   # per year. Run once per year; combine years
#                                   # explicitly with combineCards.py afterwards.
#   ./run_all.sh --cr-only          # steps 5c-5e + breakdowns (cards must exist)
#   ./run_all.sh --skip-cr          # everything except steps 5c-5e
#   ./run_all.sh --breakdown-only   # ONLY the uncertainty breakdowns (5b + 5f).
#                                   # Cheap way to add the per-category tables to
#                                   # an existing run: nothing above them re-runs.
#   ./run_all.sh --skip-breakdown   # everything except 5b + 5f
#   ./run_all.sh --with-mjj         # also run the mjj sanity fits (step 9)
#   ./run_all.sh --mjj-only         # ONLY the mjj sanity fits
#
# Intended to be run inside a tmux session.
set -e

VBSFIT_DIR="/eos/user/v/vslokenb/vbs_semilep/sensitivities/VBSfit"
MASS=125

# Data-taking period this invocation processes (override with --year=...).
# ONE year per run: the inputs config is per-year (inputs_v28_<year>.yaml,
# generated by make_inputs_from_manifest.py) and every output path below is
# tagged with the year, so the full Run-2 set is produced by running once per
# year. Cross-year cards are then built EXPLICITLY with combineCards.py --
# the year-suffixed nuisances (AK4..._2017 etc.) stay uncorrelated across
# years automatically, the unsuffixed ones correlate by shared name.
YEAR="2018"

# Signal strength used to build the SR pseudo-data in step 5d.
#   1 -> S+B pseudo-data, gives the expected significance
#   0 -> background-only pseudo-data, for a null/goodness-of-fit check
INJECT_SIGNAL=1.0

# Error estimation: strategy-0 migrad + RobustHesse -- the configuration
# the QvG postfit check (run_qvg_postfit_check.sh) has used all along --
# with --robustFit 1 supplying the asymmetric crossing error on r in the
# FitDiagnostics fits.
#
# History, so this is not "cleaned up" back into a broken state:
#   - The strategy-1 "plain HESSE, meaningful status words" experiment is
#     retired: on these cards plain HESSE cannot produce a covariance that
#     combine's --saveWithUncertainties accepts. Combine then prints
#       "The option --saveWithUncertainties will be ignored ..."
#     mid-log and writes every shape with ZERO bin errors -- which is how
#     the postfit plots carried no systematics for months (the warning was
#     eaten by a "| tail -5"; check_band_saved aborts on it now). On the
#     cards regenerated 2026-09-30, strategy-1 fits additionally fail
#     outright ("Fit failed. Done in 0.01 min"); strategy 2 ran 12h+ and
#     still tripped the same check.
#   - With RobustHesse in play the saved status words read 300/-1 even for
#     good fits: judge every fit by its values and errors, never by status.
#   - Step 5c CR-only fits keep CRFIT_MINOS (--minos all): r is frozen
#     there, so "all" is just the 2-4 norm_* rateParams and MINOS is cheap;
#     the RobustHesse symmetric error is the "(H)" fallback when a crossing
#     fails. Without RobustHesse, strategy-0 HESSE leaves zero errors and
#     read_cr_norms rightly aborts step 5d.
FIT_STRATEGY=0
CRFIT_MINOS="--minos all"

# Covariance toys for the sampled postfit band. The sampling stage DOMINATES
# the shape-saving fits' runtime and is linear in this number (prefit and
# postfit each get this many toys): 1000 toys ran 12h+ on the combined card,
# while the fit itself takes ~2 minutes. 200 is combine's default; raise it
# only for final plots, expecting the linear cost.
FD_SHAPES_NTOYS=200

# POI range for the FitDiagnostics fits. Combine's default [0, 20] puts a
# hard boundary right below the best fit and 19 units of dead range above it:
# the minimizer can touch the r=0 bound on the way in (degrading HESSE/MINOS),
# and the console printout quoted the range edges as errors. With r_hat ~ 1
# and sigma(r) ~ 0.3, [-2, 2] keeps the minimum more than 3 sigma away from
# both edges and removes the r=0 boundary entirely.
#
# Deliberately NOT applied to -M Significance (steps 4 and 9): the one-sided
# q0 discovery statistic requires the r >= 0 bound -- lifting it there would
# change the test, not fix a boundary artifact. If a FitDiagnostics fit ever
# lands at r_hat < 0, the step-5e report flags that its Z is a deficit, not a
# discovery significance.
FD_RRANGE="--rMin -2 --rMax 2"

# Categories to run the uncertainty breakdown over (steps 5b and 5f).
#
# COST: with --algo grid each of the ~17 fits per target is a likelihood SCAN,
# not a single minimization -- 61 points by default, so ~1000 minimizations per
# target and ~7000 for the full list. That is far more than the old
# --algo singles --robustFit approach, and is the price of a sigma(r) that is
# trustworthy for the norm_* rateParams.
#
# Trim this list while iterating. Lowering --points in BREAKDOWN_EXTRA is the
# other lever: the scan bias largely cancels in the quadrature difference that
# defines a group contribution, so 41 points still reproduces the exact
# contributions to ~2% (61 gives sub-1%).
BREAKDOWN_TARGETS="combined resolved_mu resolved_e boosted_mu boosted_e"

# Which run types get an uncertainty breakdown.
#   crdata  (default) only the CR-data cards -- real control-region data with a
#           blind SR Asimov. These are the numbers that describe the analysis.
#   mconly  only the Asimov-everywhere reference.
#   both    both, plus a per-category MC-only-vs-CR-data comparison table.
# The MC-only breakdown is an Asimov-only diagnostic: its control regions carry
# no data, so its "Rate params" row measures nothing real. It is off by default.
BREAKDOWN_RUNS="crdata"

# Minimizer settings for -M Significance.
#
# The significance is the one number that depends on the r=0 fit, through
# q0 = 2*(NLL_b - NLL_s+b). Strategy 0 does not reach that minimum on the
# CR-data cards -- the norm_* rateParams have to absorb ~600 signal events
# while the CRs pin them with ~350k events -- so NLL_b lands too high and Z is
# inflated. It reported 8.378 against a stat-only bound of 8.458, i.e. a 1%
# systematic degradation, where the correct answer is 4.158.
#
# r, sigma(r) and the impacts all come from the s+b fit and are unaffected,
# which is exactly why this was invisible until the b-only fit was checked.
SIG_MINIMIZER="--cminDefaultMinimizerStrategy 2 --cminFallbackAlgo Minuit2,Migrad,2:0.1 --cminFallbackAlgo Minuit2,Migrad,1:0.1"

# Extra options for uncertainty_breakdown.py. It defaults to --algo grid, which
# reads sigma(r) off the 2*deltaNLL=1 crossings of a likelihood scan instead of
# trusting MultiDimFit's own error -- the latter is unreliable for the
# unconstrained norm_* rateParams and made the "Rate params" row meaningless.
# Widen the scan (--rmin/--rmax) if a crossing warning appears; raise --points
# if the small rows look noisy.
BREAKDOWN_EXTRA=""

# mjj sanity check (step 9): rerun histograms/cards/significance on a variable
# with no BDT training in it. Asimov only -- no impacts, no breakdown, no
# CR-data hybrid. If the BDT result is real, mjj should give a clearly WEAKER
# but non-zero significance; a comparable one would mean the BDT is adding
# nothing, and a wildly larger one would mean something is wrong.
MJJ_VARIABLE="mjj_vbs"
# MJJ_HISTFILE_REL / MJJ_CARDS are set with the other output paths below,
# once YEAR is parsed (they are year-tagged like everything else).

# Merge the mjj SR templates down to this many equal-width bins.
#
# rebin() merges adjacent bins by an integer factor, so the native mjj bin count
# MUST be divisible by this number -- it raises otherwise, with the two counts
# in the message. The bins come out equal-width because the native mjj axis is
# uniform; merging a non-uniform axis would give equal-COUNT groups instead.
# Control regions are unaffected: they are always collapsed to a single
# counting bin, whatever the variable.
MJJ_SR_REBIN=20
# MJJ_OUT is set with the other output paths below, once OUTDIR exists.

# CR closure (step 5g): does the postfit nuisance configuration also describe
# the CR SHAPE? The CRs enter the fit as single counting bins, so the fit only
# ever constrains their yield -- the shape is an independent check.
CLOSURE_EXTRACT="${VBSFIT_DIR}/python/extract_postfit_params.py"
CLOSURE_PLOT="${VBSFIT_DIR}/python/plot_cr_closure.py"

RUN_MAIN=1
RUN_CR=1
RUN_BREAKDOWN=1
RUN_MJJ=0
for arg in "$@"; do
    case "${arg}" in
        --year=*)          YEAR="${arg#*=}" ;;
        --cr-only)         RUN_MAIN=0 ;;
        --skip-cr)         RUN_CR=0 ;;
        --breakdown-only)  RUN_MAIN=0; RUN_CR=0; RUN_BREAKDOWN=1 ;;
        --skip-breakdown)  RUN_BREAKDOWN=0 ;;
        --with-mjj)        RUN_MJJ=1 ;;
        --mjj-only)        RUN_MAIN=0; RUN_CR=0; RUN_BREAKDOWN=0; RUN_MJJ=1 ;;
        *) echo "Unknown option: ${arg}"; exit 1 ;;
    esac
done

case "${YEAR}" in
    2018|2017|2016_PreVFP|2016_PostVFP) ;;
    *) echo "Unknown --year '${YEAR}' (expected 2018, 2017, 2016_PreVFP or 2016_PostVFP)"; exit 1 ;;
