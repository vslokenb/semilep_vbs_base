# =======================================================
# Hybrid dataset machinery (steps 5d / 5e)
# =======================================================
#
# WHY THIS EXISTS
# ---------------
# "combine -t -1 --setParameters norm_top=X,norm_wjet=Y" does NOT fit CR data.
# -t -1 replaces the observed dataset in EVERY channel, control regions
# included, with the Asimov expectation. The CR data then enters only through
# the two numbers X and Y: the CR likelihood terms are exactly satisfied by
# construction, so the CR contributes its Asimov statistical power rather than
# its real one, and any data/MC disagreement in CR shape is erased.
#
# To actually fit CR data while keeping the SR blind, the DATASET has to be
# hybrid, not the parameter starting point:
#
#     control regions -> real data_obs, untouched
#     signal regions  -> data_obs overwritten with the MC expectation
#                        evaluated at the step-5c CR-fit norms, plus
#                        INJECT_SIGNAL x signal
#
# make_hybrid_data.py writes that file and a datacard pointing at it. The fits
# below then run with NO -t and NO --expectSignal: the pseudo-data is baked
# into the card. norm_top / norm_wjet stay FLOATING rateParams, so the CR
# constrains them from data and their uncertainty propagates into r.
#
# BLINDING: make_hybrid_data.py verifies after every build that each CR bin's
# data_obs is bit-identical to the input file and that each SR bin's data_obs
# was actually replaced. It exits nonzero otherwise, and `set -e` stops the
# pipeline before any fit sees an unblinded SR.
#
# CAVEAT: because the SR pseudo-data is built AT the CR-fit norms, the SR adds
# no independent information about norm_top / norm_wjet -- by construction it
# agrees with them. The numbers below are a sensitivity estimate under the
# CR-measured background normalization, not a measurement.

build_hybrid_one() {
    # $1 = output dir, $2 = source datacard, $3 = "norm_top=..,norm_wjet=.."
    python3 "${HYBRID_SCRIPT}" \
        --datacard "$2" \
        --norms "$3" \
        --inject-signal "${INJECT_SIGNAL}" \
        --mass ${MASS} \
        --outdir "$1"
}


build_hybrid_target() {
    local target="$1"
    local crcase="${CR_SOURCE[$target]}"
    local setpars a b

    setpars=$(cr_norms_for "${crcase}") || {
        echo "  [skip] ${target}: no usable CR norms from ${crcase}"
        return 1
    }

    echo ""
    echo "--- Hybrid dataset: ${target}  (norms from ${crcase}: ${setpars}) ---"

    case "${target}" in
        resolved|boosted)
            # Topology cards must be assembled from per-category hybrids built
            # with the TOPOLOGY norms, so build a private copy of each here
            # rather than reusing the per-category output above.
            if [ "${target}" = "resolved" ]; then a=resolved_mu; b=resolved_e
            else                                  a=boosted_mu;  b=boosted_e; fi
            for ch in "${a}" "${b}"; do
                [ -f "${CARDDIR}/${ch}/datacard.txt" ] || {
                    echo "  [skip] ${target}: ${ch} datacard not found"; return 1; }
                build_hybrid_one "${CRDATA_CARDS}/${target}/${ch}" \
                                 "${CARDDIR}/${ch}/datacard.txt" "${setpars}"
            done
            mkdir -p "${CRDATA_CARDS}/${target}"
            combineCards.py \
                "${CRDATA_CARDS}/${target}/${a}/datacard.txt" \
                "${CRDATA_CARDS}/${target}/${b}/datacard.txt" \
                > "${CRDATA_CARDS}/${target}/datacard.txt"
            check_shapes_resolve "${CRDATA_CARDS}/${target}/datacard.txt"
            ;;
        *)
            [ -f "${CARDDIR}/${target}/datacard.txt" ] || {
                echo "  [skip] ${target}: datacard not found"; return 1; }
            build_hybrid_one "${CRDATA_CARDS}/${target}" \
                             "${CARDDIR}/${target}/datacard.txt" "${setpars}"
            ;;
    esac
}


# Print the post-fit value of every rateParam in a fitDiagnostics file.
#
# WHERE THE NORMALIZATIONS ARE REPORTED
# -------------------------------------
# Three different places, and they answer different questions:
#
#   1. THIS function / fitDiagnostics_*.root -- the authoritative post-fit
#      norm_top and norm_wjet with uncertainties. Always present, because
#      FitDiagnostics stores every floating parameter in the RooFitResult.
#      This is what you quote as "the CR-measured normalization".
#
#   2. The impact plot -- norm_top / norm_wjet appear as ROWS in the impacts
#      only if combineTool put them in the nuisance list it scans. Unconstrained
#      rateParams usually are included, but they are drawn with no prefit
#      constraint band, and some plotImpacts.py versions drop or mislabel them.
#      Do not rely on the plot for the central values; check impacts.json.
#
#   3. The combine stdout in the log -- prints them, but without covariance and
#      only for whichever fit just ran.
#
# With --robustFit (steps 5/5e) r carries asymmetric NLL-crossing errors;
# the norm_* errors are symmetric RobustHesse values and print as
# "(Hessian)". Status words read 300/-1 with RobustHesse -- not meaningful.
report_postfit_norms() {
    local fdfile="$1"
    local label="$2"
    [ -f "${fdfile}" ] || { echo "  [warn] no ${fdfile}"; return 0; }
    python3 - "${fdfile}" "${label}" <<'PYEOF'
import re
import sys
import ROOT
ROOT.gErrorIgnoreLevel = ROOT.kError
path, label = sys.argv[1], sys.argv[2]
RX = re.compile(r"^norm_")
f = ROOT.TFile.Open(path)
print("")
print("  post-fit normalizations (%s)" % label)
for fitname, what in (("fit_s", "S+B fit"), ("fit_b", "B-only fit")):
    fr = f.Get(fitname)
    if not fr:
        continue
    pars = fr.floatParsFinal()
    # Discover norm_* so decorrelated per-topology names are all reported.
    names = sorted(pars.at(i).GetName() for i in range(pars.getSize())
                   if RX.search(pars.at(i).GetName()))
    rows = []
    for name in names + ["r"]:
        p = pars.find(name)
        if not p:
            continue
        lo, hi = abs(p.getErrorLo()), abs(p.getErrorHi())
        if lo == 0.0 or hi == 0.0:
            rows.append("    %-22s %8.4f +/- %.4f (Hessian)" % (name, p.getVal(), p.getError()))
        else:
            rows.append("    %-22s %8.4f  -%.4f / +%.4f" % (name, p.getVal(), lo, hi))
    if rows:
        print("   %s  (status=%d covQual=%d)" % (what, fr.status(), fr.covQual()))
        print("\n".join(rows))
f.Close()
PYEOF
}


