import sys
import ROOT
ROOT.gErrorIgnoreLevel = ROOT.kError
path, target = sys.argv[1], sys.argv[2]
f = ROOT.TFile.Open(path)
if not f or f.IsZombie():
    print("%s: ERROR -- no fitDiagnostics file at %s (combine crashed?)" % (target, path))
    sys.exit(0)

rhat = None
fr = f.Get("fit_s")
if not fr:
    print("%s: ERROR -- no fit_s in %s" % (target, path))
else:
    p = fr.floatParsFinal().find("r")
    if not p:
        print("%s: ERROR -- no POI 'r' in fit_s" % target)
    else:
        rhat = p.getVal()
        lo, hi = abs(p.getErrorLo()), abs(p.getErrorHi())
        if lo == 0.0 or hi == 0.0:
            err = "+/- %.4f (Hessian)" % p.getError()
        else:
            err = "-%.4f/+%.4f" % (lo, hi)
        print("%s: r = %.4f %s   (fit_s status=%d covQual=%d)"
              % (target, rhat, err, fr.status(), fr.covQual()))

ts, tb = f.Get("tree_fit_sb"), f.Get("tree_fit_b")
if not ts or not tb:
    print("%s: ERROR -- fit trees missing (fit crashed?)" % target)
    sys.exit(0)
ts.GetEntry(0)
tb.GetEntry(0)
q0 = 2.0 * (tb.nll_min - ts.nll_min)
# r floats in [-2, 2] (FD_RRANGE), so r_hat < 0 is possible: q0 is then
# measuring a DEFICIT and sqrt(q0) is not a discovery significance.
note = ""
if rhat is not None and rhat < 0.0:
    note = "   [r_hat < 0: deficit -- NOT a discovery significance]"
print("%s: q0 = %.3f  Significance: %.3f%s"
      % (target, q0, max(q0, 0.0) ** 0.5, note))
PYEOF
)
        echo "${result}"
        {
            echo ""
            echo "--- ${target}  (norms from ${CR_SOURCE[$target]}) ---"
            echo "${result}"
        } >> "${CRSENS_FILE}"
    done

    echo ""
    echo "  Hybrid significances written to ${CRSENS_FILE}"

    # FitDiagnostics on the hybrid combined card
    if [ -f "${CRDATA_CARDS}/combined/datacard.txt" ]; then
        echo ""
        echo "--- FitDiagnostics (combined, hybrid) ---"
        mkdir -p "${CRDATA_OUT}/fitdiagnostics"
        cd "${CRDATA_OUT}/fitdiagnostics"
        run_combine_logged fitdiag_hybrid.log \
            -M FitDiagnostics \
            -d "${CRDATA_CARDS}/combined/datacard.txt" \
            -m ${MASS} \
            --saveShapes --saveWithUncertainties --numToysForShapes ${FD_SHAPES_NTOYS} \
            --cminDefaultMinimizerStrategy ${FIT_STRATEGY} \
            --robustHesse 1 --robustFit 1 \
            ${FD_RRANGE} \
            --name _hybrid
        check_band_saved fitdiag_hybrid.log
        cd "${VBSFIT_DIR}"
        echo "  -> ${CRDATA_OUT}/fitdiagnostics/fitDiagnostics_hybrid.root"
        echo "     (the post-fit norm_* values here are constrained by CR DATA)"
        report_postfit_norms \
            "${CRDATA_OUT}/fitdiagnostics/fitDiagnostics_hybrid.root" \
            "combined, CR data + SR Asimov" \
            | tee "${CRDATA_OUT}/postfit_norms_combined.txt"
        write_run_readme "${CRDATA_OUT}/fitdiagnostics" crdata

        # -----------------------------------------------------------------
        # Step 5g: CR closure at full BDT binning
        #
        # The CRs are single counting bins in the fit, so combine constrained
        # only their yield and its shapes_fit_s output has no shape-level
        # postfit uncertainty for them. This rebuilds each CR from coffea at
        # full binning, morphs it by the fitted pulls, and propagates the
        # postfit covariance for the band. Real CR data is shown -- the CRs
        # are unblinded by design.
        #
        # The extracted covariance is the RobustHesse one -- the same matrix
        # the band sampler uses, positive definite by construction.
        # -----------------------------------------------------------------
        _fd="${CRDATA_OUT}/fitdiagnostics/fitDiagnostics_hybrid.root"
        if [ -f "${CLOSURE_EXTRACT}" ] && [ -f "${CLOSURE_PLOT}" ]; then
            echo ""
            echo "--- Step 5g: CR closure (postfit CR shape vs data) ---"
            mkdir -p "${CRDATA_OUT}/cr_closure"
            for reg in resolved_mu resolved_e boosted_mu boosted_e; do
                _js="${CRDATA_OUT}/cr_closure/postfit_params_${reg}.json"
                # extract_postfit_params.py needs PyROOT -> CMSSW python3.
                if ! python3 "${CLOSURE_EXTRACT}" \
                        --fitfile "${_fd}" \
                        --region "${reg}" \
                        --output "${_js}"; then
                    echo "  [warn] ${reg}: could not extract postfit params"
                    continue
                fi
                # plot_cr_closure.py needs coffea -> apptainer.
                pyrun python3 python/plot_cr_closure.py \
                    --config ${CONFIG_REL} \
                    --binning config/binning_example.yaml \
                    --postfit-json "${OUTDIR_REL}/crdata_srasimov/cr_closure/postfit_params_${reg}.json" \
                    --region "${reg}" \
                    --cr-only-norms "${CRDIR}/cr_only_norms.txt" \
                    --outdir "${OUTDIR_REL}/crdata_srasimov/cr_closure" \
                    || echo "  [warn] ${reg}: closure plotting failed"
            done
            write_run_readme "${CRDATA_OUT}/cr_closure" crdata
        else
            echo "  [skip] CR closure: extract_postfit_params.py / "
            echo "         plot_cr_closure.py not found in python/"
        fi
    fi

    # Impacts on the hybrid dataset.
    #
    # The empty 3rd and 4th arguments matter:
    #   3rd = no --setParameters. The CR-derived norms are already baked into
    #         the card's SR observation; re-injecting them would only move the
    #         fit's starting point, and they must stay FLOATING so the CR data
    #         constrains them and that uncertainty propagates into r.
    #   4th = no "-t -1 --expectSignal 1". Empty, not omitted -- omitting it
    #         restores the Asimov default and discards the CR data.
    if check_impacts_script_supports_data; then
        for target in combined resolved_mu resolved_e boosted_mu boosted_e; do
            card="${CRDATA_CARDS}/${target}/datacard.txt"
            [ -f "${card}" ] || continue
            echo ""
            echo "--- Impacts (hybrid): ${target} ---"
            bash "${IMPACTS_SCRIPT}" \
                "${card}" \
                "${CRDATA_OUT}/impacts_${target}" \
                "" ""
            check_impacts_has_norms "${CRDATA_OUT}/impacts_${target}"
            write_run_readme "${CRDATA_OUT}/impacts_${target}" crdata
        done
    fi

fi


