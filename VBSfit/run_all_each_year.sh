# =======================================================
# CR-only fit machinery (step 5c)
# =======================================================
#
# Fits REAL DATA in the TTCR and WCR while the SR bins are removed from the
# likelihood via combine's --channel-masks. This gives data-driven post-fit
# values and uncertainties for norm_top / norm_wjet without unblinding the SR.
#
# IMPORTANT -- mask parameter names:
# text2workspace.py --channel-masks creates, for every BIN in the datacard, a
# separate RooRealVar named  mask_<bin>.  The "mask_" prefix is generated by
# the tool; it is part of the variable name, not a label. So a bin called
# "resolved_mu" is controlled by a variable called "mask_resolved_mu", and
# BOTH objects exist in the workspace.
#
#   - per-SR cards (written directly by make_datacards.py):
#         bins  = resolved_mu, ttbar_cr_resolved_mu, w_cr_resolved_mu
#         masks = mask_resolved_mu, mask_ttbar_cr_resolved_mu, ...
#     -> only the SR mask is set to 1; the CR masks stay 0 so the CRs are fit.
#
#   - combined card: ALSO written directly by make_datacards.py (NOT via
#     combineCards.py), so its bins keep their literal names:
#         masks = mask_resolved_mu, mask_resolved_e, mask_boosted_mu, mask_boosted_e
#
#   - topology cards: built here by combineCards.py, which prefixes bins with
#     ch1_/ch2_ in the order the cards are given:
#         masks = mask_ch1_<first sr>, mask_ch2_<second sr>
#
# If a mask name is wrong, combine only WARNS and then fits the SR with real
# data -- i.e. silently unblinds. check_masks_exist() aborts instead.
#
# r is frozen: signal processes are not written into the CR channels, so once
# the SRs are masked r has no effect on the likelihood at all.

declare -A CR_CARD
