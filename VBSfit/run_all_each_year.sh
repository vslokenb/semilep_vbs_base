# --- Blinding safety check ---------------------------------------------
check_masks_exist() {
    local ws="$1"
    local masks="$2"
    python3 - "${ws}" "${masks}" <<'PYEOF'
import sys
import ROOT
ROOT.gErrorIgnoreLevel = ROOT.kError
ws_path, masks = sys.argv[1], sys.argv[2].split(',')
f = ROOT.TFile.Open(ws_path)
w = f.Get("w")
if not w:
    print("ERROR: no RooWorkspace 'w' in %s" % ws_path)
    sys.exit(1)
missing = [m for m in masks if not w.var(m)]
if missing:
    have = sorted(v.GetName() for v in w.allVars()
                  if v.GetName().startswith("mask_"))
    print("ERROR: mask parameters not found in workspace: %s" % ", ".join(missing))
    if have:
        print("       workspace has these mask parameters: %s" % ", ".join(have))
    else:
        print("       workspace has NO mask_* parameters at all --")
        print("       it was probably built without --channel-masks.")
        print("       Delete %s and rerun." % ws_path)
    sys.exit(1)
print("  mask check OK: %s" % ", ".join(masks))
PYEOF
}


run_cr_case() {
    local case="$1"
    local card="${CR_CARD[$case]}"
    local masks="${CR_MASKS[$case]}"
    local outdir="${CRDIR}/${case}"

    echo ""
    echo "--- CR-only fit: ${case} ---"
    mkdir -p "${outdir}"

    if [ ! -f "${card}" ]; then
        echo "  [skip] datacard not found: ${card}"
        return 0
    fi

    local ws="${outdir}/workspace_crmask.root"
    # Rebuild the workspace when it is missing OR older than the datacard:
    # steps 1-2 regenerate the cards, and a cached workspace built from an
    # earlier card silently fits an outdated model (or fails outright if the
    # cached file is from a broken intermediate state).
    if [ ! -f "${ws}" ] || [ "${card}" -nt "${ws}" ]; then
        rm -f "${ws}"
        # Piping to tail hides the exit status, so check for the output file
        # explicitly -- otherwise a text2workspace failure only surfaces later
        # as a confusing "workspace does not exist" from check_masks_exist.
        text2workspace.py "${card}" --channel-masks -o "${ws}" -m ${MASS} 2>&1 | tail -3
        if [ ! -f "${ws}" ]; then
            echo "ERROR: text2workspace.py produced no workspace for '${case}'."
            echo "       Card: ${card}"
            echo "       Rerun the command above without '| tail -3' to see the full error."
            return 1
        fi
    fi

    check_masks_exist "${ws}" "${masks}"

    local set_masks
    set_masks=$(echo "${masks}" | tr ',' '\n' | sed 's/$/=1/' | paste -sd, -)

    # Freeze the constrained nuisances.
    #
    # With the SR masked, a per-SR card has only TWO data points left (the
    # TTCR and WCR counting bins) while the likelihood still carries every
    # shape systematic plus the prop_bin Barlow-Beeston params -- of order
    # 150 floating parameters against 2 numbers. They are prior-constrained
    # so the fit is not formally singular, but the Hessian is near-degenerate
    # in nearly every direction, which produces status=300 / covQual=-1 /
    # nan MINOS errors, and outright crashes on the larger cards.
    #
    # Two counting bins can only measure two things, so float only norm_top
    # and norm_wjet. The systematics are not dropped from the analysis -- they
    # are still fully floating in the SR+CR fits of steps 4/5/5e, where the
    # rateParams are also free. This step exists purely to read the CR-measured
    # central values.
    #
    # Errors: MINOS (--minos all) over the 2-4 floating norm_* rateParams,
    # backed by --robustHesse 1 -- at strategy 0, plain HESSE leaves zero
    # errors (status=300) and read_cr_norms would refuse the norms, aborting
    # step 5d. MINOS asymmetric errors are printed when the crossings
    # succeed; the RobustHesse symmetric error is the "(H)" fallback.
    # Side effect: status/covQual from these fits read 300/-1 even when the
    # fit is fine -- judge them by the norm values and errors instead.
    local freeze="r,${masks},allConstrainedNuisances"

    cd "${outdir}"
    combine -M FitDiagnostics \
        -d "${ws}" \
        -m ${MASS} \
        --setParameters "${set_masks}" \
        --freezeParameters "${freeze}" \
        ${CRFIT_MINOS} \
        --cminDefaultMinimizerStrategy ${FIT_STRATEGY} \
        --robustHesse 1 \
        --name "_cronly_${case}" \
        2>&1 | tail -8
    cd "${VBSFIT_DIR}"

    local fdfile="${outdir}/fitDiagnostics_cronly_${case}.root"
    if [ ! -f "${fdfile}" ]; then
        echo "  [warn] ${case}: no fitDiagnostics output -- combine crashed."
        echo "         Rerun the command above without '| tail -8' to see why."
    fi
}


collect_cr_results() {
    local outfile="${CRDIR}/cr_only_norms.txt"
    {
        echo "CR-only fits to data, SRs masked via --channel-masks"
        echo "Generated: $(date)"
        echo "============================================================"
    } > "${outfile}"

    python3 - "${CRDIR}" "${CR_CASES}" <<'PYEOF' | tee -a "${outfile}"
import os, sys
import ROOT
ROOT.gErrorIgnoreLevel = ROOT.kError

import re
crdir, cases = sys.argv[1], sys.argv[2].split()

# Parameter names are DISCOVERED, not assumed: decorrelating the
# normalizations per topology renames them (norm_top -> norm_top_resolved /
# norm_top_boosted), and the number of them per case then differs too --
# a per-category card carries one pair, the combined card two.
RX = re.compile(r"^norm_")

hdr = f"{'case':<16}{'parameter':<22}{'value':>26}{'status':>8}{'covQual':>9}"
print(hdr)
print("-" * len(hdr))
for case in cases:
    path = os.path.join(crdir, case, f"fitDiagnostics_cronly_{case}.root")
    if not os.path.exists(path):
        print(f"{case:<16}{'MISSING (fit produced no output)':<22}")
        continue
    f = ROOT.TFile.Open(path)
    fr = f.Get("fit_s")
    if not fr:
        print(f"{case:<16}{'NO fit_s IN FILE':<22}")
        f.Close()
        continue
    pars = fr.floatParsFinal()
    found = [pars.at(i) for i in range(pars.getSize())
             if RX.search(pars.at(i).GetName())]
    if not found:
        print(f"{case:<16}{'no norm_* parameter':<22}")
        f.Close()
        continue
    for j, p in enumerate(sorted(found, key=lambda v: v.GetName())):
        lo, hi = abs(p.getErrorLo()), abs(p.getErrorHi())
        if lo == 0.0 or hi == 0.0:      # failed MINOS crossing
            val = f"{p.getVal():.4f} +/- {p.getError():.4f} (H)"
        else:
            val = f"{p.getVal():.4f} -{lo:.4f}/+{hi:.4f}"
        left = case if j == 0 else ""
        tail = f"{fr.status():>8}{fr.covQual():>9}" if j == 0 else ""
        print(f"{left:<16}{p.GetName():<22}{val:>26}{tail}")
    f.Close()
