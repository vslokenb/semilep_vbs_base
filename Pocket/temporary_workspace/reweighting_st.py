def ratio_function(x):
    """Awkward-array-safe cubic spline."""
    
    x = ak.Array(x)

    # mask regions
    below = x <= _pchip_knots[0]
    above = x >= _pchip_knots[-1]
    inside = ~(below | above)

    # Interval index for inside region:
    # For each x, find last knot <= x.
    # idx = ak.sum(x[..., None] >= _pchip_knots, axis=-1) - 1

    idx = ak.sum(x[..., None] >= _pchip_knots, axis=-1) - 1
    
    # inside = (x > _pchip_knots[0]) & (x < _pchip_knots[-1])

    idx = ak.where(inside, idx, 0)
    # dx only where inside
    dx = x - _pchip_knots[idx]

    # coefficients selected per element
    a3 = _pchip_coeffs[0][idx]
    a2 = _pchip_coeffs[1][idx]
    a1 = _pchip_coeffs[2][idx]
    a0 = _pchip_coeffs[3][idx]

    # cubic polynomial
    mid_val = ((a3 * dx + a2) * dx + a1) * dx + a0

    # combine
    out = ak.where(below, _pchip_values[0],
          ak.where(above, 1.0,
                   mid_val))

    return out
